"""Reproduce the C++ level table directly from the unmodified AS2 export."""
from pathlib import Path
import re
import json
from urllib.parse import parse_qsl

root = Path(__file__).resolve().parents[1]
source = (root / 'scripts/frame_11/DoAction.as').read_text()
entries = re.findall(r'var data(\d+) = "([^"]*)";', source)
assert len(entries) == 50
lines = ['// Generated by tools/extract_levels.py; do not edit level data by hand.',
         '#include "game.hpp"', 'namespace bloons {',
         'const Array<Level, 50>& levels() {',
         'static const Array<Level, 50> data{{']
for expected, (number, encoded) in enumerate(entries, 1):
    assert int(number) == expected
    values = dict(parse_qsl(encoded))
    cells = [[int(values[f'{x}-{y}']) for y in range(13)] for x in range(24)]
    assert sum(v == 4 for col in cells for v in col) == 1
    grid = ','.join('{{' + ','.join(map(str, col)) + '}}' for col in cells)
    lines.append('Level{' + ','.join([number, values['target'], values['darts'],
                 json.dumps(values['title']), '{{' + grid + '}}']) + '},')
lines += ['}};', 'return data;', '}', '}']
(root / 'src/levels.cpp').write_text('\n'.join(lines) + '\n')
print('Extracted all 50 original levels (15,600 cells).')
