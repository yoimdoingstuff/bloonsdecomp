"""Generate native reference geometry from the supplied SWF, without executing it."""
from functools import lru_cache
import json
from pathlib import Path
import sys
from inspect_swf import inspect

IDENTITY = [1, 0, 0, 1, 0, 0]
ROOT = Path(__file__).resolve().parents[1]


def union(rectangles):
    rs = [r for r in rectangles if r is not None]
    if not rs:
        return None
    return [min(r[0] for r in rs), max(r[1] for r in rs),
            min(r[2] for r in rs), max(r[3] for r in rs)]


def transform(rect, matrix):
    a, b, c, d, tx, ty = matrix
    points = [(a*x+c*y+tx, b*x+d*y+ty)
              for x in rect[:2] for y in rect[2:]]
    return [min(x for x, y in points), max(x for x, y in points),
            min(y for x, y in points), max(y for x, y in points)]


def extract(path):
    data = inspect(path)
    definitions = data['definitions']

    @lru_cache(None)
    def bounds(character, all_frames=True):
        definition = definitions.get(str(character), {})
        if 'bounds' in definition:
            return [definition['bounds'][k] for k in ('xmin', 'xmax', 'ymin', 'ymax')]
        frames = definition.get('frames', [])
        if not all_frames:
            frames = frames[:1]
        placements = [p for frame in frames for p in frame.values()]
        placements += definition.get('records', [])
        return union([transform(r, p.get('matrix', IDENTITY)) for p in placements
                      if (r := bounds(p['character'], all_frames)) is not None])

    def frame_bounds(frame):
        return union([transform(r, p.get('matrix', IDENTITY)) for p in frame.values()
                      if (r := bounds(p['character'], False)) is not None])

    def named(timeline, frame, name):
        return next(p for p in timeline['frames'][frame-1].values() if p.get('name') == name)

    def fmt(values):
        return '{' + ','.join(format(v, '.15g') for v in values) + '}'

    def rect(r):
        return [r[0], r[2], r[1]-r[0], r[3]-r[2]]

    def constant(name, values):
        return 'inline constexpr Affine ' + name + fmt(values) + ';'

    play = data['root']
    root_placements = {p['name']: p for p in play['frames'][54].values() if p.get('name')}
    result = [
        '// Generated by tools/extract_swf.py. Source SHA-256: ' + data['sha256'],
        '#pragma once', '#include "storage.hpp"', 'namespace bloons::swf {',
        'struct Affine { double a,b,c,d,tx,ty; };',
        'struct Bounds { double x,y,w,h; };',
        'struct Sprite { int id; Bounds bounds; };',
        'struct Pose { Affine inner; Bounds hit; };',
        'struct BalloonStyle { int id,body,popSound; Array<Pose,80> poses; };',
        'struct LevelButton { int number,sprite; Affine placement; Bounds hit; };',
        f'inline constexpr double frameRate = {data["frame_rate"]};',
        f'inline constexpr double playareaX = {root_placements["playarea"]["matrix"][4]};',
        f'inline constexpr double playareaY = {root_placements["playarea"]["matrix"][5]};',
        constant('dart', root_placements['dart']['matrix']),
        constant('extraDart', root_placements['dart_2']['matrix']),
        constant('dartTip', named(definitions['39'], 1, 'hitBit')['matrix']),
        constant('boomerangHit', named(definitions['39'], 2, 'hitBit')['matrix']),
        constant('tackHit', named(definitions['12'], 1, 'hitBit')['matrix']),
        constant('spikeyHit', named(definitions['8'], 1, 'hitbit')['matrix']),
        constant('monkeyArm', named(definitions['155'], 1, 'arm')['matrix']),
        constant('armTip', named(definitions['152'], 1, 'tip')['matrix']),
        constant('monkeyEyes', named(definitions['155'], 1, 'eyes')['matrix']),
        constant('armThrow', named(definitions['155'], 1, 'armthrow')['matrix']),
        constant('gameui', root_placements['gameui']['matrix']),
        constant('ui', named(definitions['305'], 11, 'ui')['matrix']),
        constant('aimInner', named(definitions['171'], 1, 'inner')['matrix']),
        constant('arrowKeys', root_placements['arrowkeys']['matrix']),
        constant('losePanel', root_placements['losepanel_mc']['matrix']),
        constant('loseText', next(iter(definitions['629']['frames'][24].values()))['matrix']),
        'inline constexpr Bounds dartHitBounds' + fmt(rect(bounds(35, False))) + ';',
        'inline constexpr Bounds boomerangHitBounds' + fmt(rect(bounds(38, False))) + ';',
        'inline constexpr Bounds tackHitBounds' + fmt(rect(bounds(11, False))) + ';',
        'inline constexpr Bounds spikeyHitBounds' + fmt(rect(bounds(6, False))) + ';',
        constant('boomerangArt', next(p['matrix'] for p in definitions['39']['frames'][1].values()
                                      if p.get('name') == 'boomerang')),
    ]
    sprites = [(int(k), bounds(int(k))) for k, v in definitions.items() if v['tag'] == 39]
    sprites = [(k, b) for k, b in sprites if b is not None]
    result.append(f'inline constexpr Array<Sprite,{len(sprites)}> sprites{{{{')
    result += ['{' + str(k) + ',' + fmt(rect(b)) + '},' for k, b in sorted(sprites)]
    result += ['}};', 'inline constexpr Bounds spriteBounds(int id) {',
               'for(auto s:sprites) if(s.id==id) return s.bounds;', 'return {0,0,0,0};', '}']
    ids = [145, 143, 138, 134, 117, 130, 101, 108, 30, 25, 43, 53]
    result.append(f'inline constexpr Array<BalloonStyle,{len(ids)}> balloons{{{{')
    for identifier in ids:
        definition = definitions[str(identifier)]
        body = named(definition, 1, 'inner')['character']
        sound = next((s['sound'] for s in definition['start_sounds'] if s['frame'] == 98), 0)
        result.append('{' + f'{identifier},{body},{sound},' + '{{')
        for frame in definition['frames'][:80]:
            inner = next(p for p in frame.values() if p.get('name') == 'inner')
            result.append('{' + fmt(inner.get('matrix', IDENTITY)) + ',' + fmt(rect(frame_bounds(frame))) + '},')
        result.append('}}},')
    result += ['}};', 'inline constexpr int balloonSymbol(int type,int colour) {',
               'constexpr int normal[]{145,143,138,134};',
               'constexpr int special[]{0,0,117,130,155,101,108,30,25,43,53};',
               'return type==1?normal[colour%4]:type<=10?special[type]:type==21?63:type==22?82:80;',
               '}', 'inline constexpr const BalloonStyle* balloonStyle(int id) {',
               'for(const auto& b:balloons) if(b.id==id) return &b;', 'return nullptr;', '}']
    result.append('inline constexpr Array<Affine,9> throwPoses{{')
    result += [fmt(next(iter(frame.values()))['matrix']) + ',' for frame in definitions['154']['frames'][1:]]
    result.append('}};')
    thumbs = named(data['root'], 54, 'thumbs')['matrix']
    result.append('inline constexpr Array<LevelButton,50> levelButtons{{')
    for placement in sorted(definitions['606']['frames'][0].values(), key=lambda p: int(p['name'])):
        matrix = placement['matrix'][:]
        matrix[4] += thumbs[4]
        matrix[5] += thumbs[5]
        hit = transform(bounds(placement['character'], False), matrix)
        result.append('{' + f'{int(placement["name"])},{placement["character"]},' + fmt(matrix) + ',' + fmt(rect(hit)) + '},')
    result.append('}};')
    result.append(constant('unlimitedDarts', named(data['root'], 54, 'unlimdarts')['matrix']))
    result.append('inline constexpr Array<Affine,1955> cloudPoses{{')
    result += [fmt(next(p['matrix'] for p in frame.values() if p.get('name') == 'clouds')) + ','
               for frame in definitions['187']['frames']]
    result.append('}};')
    # Button records and text placements are retained in the compact audit report.
    report = {k: v for k, v in data.items() if k not in ('definitions', 'root')}
    report['root'] = {'labels': data['root']['labels'], 'play': root_placements}
    report['definitions'] = {k: {n: v for n, v in d.items() if n not in ('frames', 'tag_counts')}
                             for k, d in definitions.items()}
    report['named_placements'] = {
        k: [p for p in (d.get('frames') or [{}])[0].values() if p.get('name')]
        for k, d in definitions.items() if any(p.get('name') for p in (d.get('frames') or [{}])[0].values())}
    result += ['}', '']
    (ROOT / 'src/swf_data.hpp').write_text('\n'.join(result))
    reference = ROOT / 'reference/swf_metadata.json'
    reference.parent.mkdir(exist_ok=True)
    reference.write_text(json.dumps(report, indent=2) + '\n')
    print(f'Extracted {data["frame_rate"]} FPS, {len(sprites)} sprite bounds, 960 balloon poses, '
          f'1955 cloud poses, labels, sound linkage and placements.')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit('Usage: python tools/extract_swf.py path/to/Bloons_decrypted.swf')
    extract(Path(sys.argv[1]))
